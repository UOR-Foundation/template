"""Subset the brand kit's fonts for the page, and write the font-face rules with
metric-matched fallbacks and font-display optional: no swap, no layout shift, and the
brand font whenever it is ready in time (always, from the second visit on).

    python -I bootstrap/brand-fonts.py            subset .brand-src/ fonts into site/fonts, update brand.lock, write site/brand/fonts.css
    python -I bootstrap/brand-fonts.py --check    recompute and compare the hashes in brand.lock

Sources come from `node bootstrap/brand-sync.mjs --sync`. Needs fonttools and
brotli (both in the SDK image). The fallbacks are Arial for Geist and Archivo
and Courier New for Geist Mono, with size-adjust and the ascent, descent and
line-gap overrides computed from the metrics of both fonts."""
import hashlib, json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOCK = os.path.join(ROOT, "brand.lock")
SRC = os.path.join(ROOT, ".brand-src")
FALLBACKS = {
    "Archivo": ("Arial", "C:/Windows/Fonts/arial.ttf", "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf"),
    "Geist": ("Arial", "C:/Windows/Fonts/arial.ttf", "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf"),
    "Geist Mono": ("Courier New", "C:/Windows/Fonts/cour.ttf", "/usr/share/fonts/truetype/liberation/LiberationMono-Regular.ttf"),
}
FAMILIES = {
    "Archivo-SemiBold": ("Archivo", 600),
    "Geist-Regular": ("Geist", 400),
    "Geist-Medium": ("Geist", 500),
    "GeistMono-Regular": ("Geist Mono", 400),
    "GeistMono-Medium": ("Geist Mono", 500),
}


def sha256(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def metrics(path):
    from fontTools.ttLib import TTFont
    f = TTFont(path)
    upm = f["head"].unitsPerEm
    hhea = f["hhea"]
    os2 = f["OS/2"]
    # Average advance of the Latin lowercase, the width that matters for body text.
    cmap = f.getBestCmap()
    hmtx = f["hmtx"]
    widths = [hmtx[cmap[ord(c)]][0] for c in "abcdefghijklmnopqrstuvwxyz " if ord(c) in cmap]
    avg = sum(widths) / len(widths)
    return {"upm": upm, "ascent": hhea.ascent, "descent": abs(hhea.descent), "gap": hhea.lineGap, "avg": avg,
            "xavg": os2.xAvgCharWidth}


def subset(src, dst, unicodes, features):
    subprocess.run([sys.executable, "-I", "-m", "fontTools.subset", src, f"--unicodes={unicodes}", f"--layout-features={features}",
                    "--flavor=woff2", "--no-hinting", "--desubroutinize", "--name-IDs=1,2,3,4,6", f"--output-file={dst}"], check=True)


def main(check_only):
    lock = json.load(open(LOCK))
    fonts = lock["fonts"]
    changed = False
    done = set()
    rules = ["/* GENERATED by bootstrap/brand-fonts.py from brand.lock; do not edit. */"]
    for font in fonts["files"]:
        src = os.path.join(SRC, font["from"])
        dst = os.path.join(ROOT, font["to"])
        stem = os.path.splitext(os.path.basename(font["to"]))[0]
        family, weight = FAMILIES[stem]
        if check_only:
            got = sha256(dst) if os.path.exists(dst) else "missing"
            if got != font["sha256"]:
                print(f"brand-fonts: {font['to']} is {got}, brand.lock says {font['sha256']}")
                changed = True
            continue
        if not os.path.exists(src):
            sys.exit(f"brand-fonts: {src} is missing; run node bootstrap/brand-sync.mjs --sync")
        if sha256(src) != font["source_sha256"]:
            sys.exit(f"brand-fonts: {src} does not match brand.lock")
        subset(src, dst, fonts["unicodes"], fonts["layout_features"])
        font["sha256"] = sha256(dst)
        changed = True
        # Metric-matched fallback for this family, computed once per family
        # from its first (regular) file.
        m = metrics(dst)
        name, *candidates = FALLBACKS[family]
        fb_path = next((p for p in candidates if os.path.exists(p)), None)
        if fb_path and family not in done:
            done.add(family)
            fb = metrics(fb_path)
            size_adjust = (m["avg"] / m["upm"]) / (fb["avg"] / fb["upm"])
            asc = m["ascent"] / m["upm"] / size_adjust
            desc = m["descent"] / m["upm"] / size_adjust
            gap = m["gap"] / m["upm"] / size_adjust
            fallback = (f'@font-face {{ font-family: "{family} Fallback"; src: local("{name}"); '
                        f"size-adjust: {size_adjust*100:.2f}%; ascent-override: {asc*100:.2f}%; "
                        f"descent-override: {desc*100:.2f}%; line-gap-override: {gap*100:.2f}%; }}")
            if fallback not in rules:
                rules.append(fallback)
        rules.append(f'@font-face {{ font-family: "{family}"; src: url("../fonts/{os.path.basename(font["to"])}") format("woff2"); '
                     f"font-weight: {weight}; font-style: normal; font-display: optional; }}")
        print(f"brand-fonts: {font['to']} {os.path.getsize(dst)} bytes")
    if check_only:
        if changed:
            sys.exit(1)
        print("brand-fonts: every subset matches brand.lock")
        return
    rules.append(':root { --font-sans: "Geist", "Geist Fallback", Arial, sans-serif; '
                 '--font-display: "Archivo", "Archivo Fallback", Arial, sans-serif; '
                 '--font-mono: "Geist Mono", "Geist Mono Fallback", "Courier New", monospace; }')
    open(os.path.join(ROOT, "site/brand/fonts.css"), "w", newline="\n").write("\n".join(rules) + "\n")
    json.dump(lock, open(LOCK, "w", newline="\n"), indent=2)
    open(LOCK, "a", newline="\n").write("\n")
    print("brand-fonts: brand.lock and site/brand/fonts.css written")


if __name__ == "__main__":
    main("--check" in sys.argv)
